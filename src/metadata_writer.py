"""
src/metadata_writer.py
Stage E — Video Metadata Generation.

Generates suggested YouTube title, description, hashtags, and video_metadata.txt.
Uses Gemini if available; falls back to template-based generation.
"""

from __future__ import annotations

import logging
import os
import re
from datetime import datetime
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)


class MetadataWriter:
    """Generate YouTube upload metadata for the finished Short."""

    def __init__(self, config: dict):
        self.cfg = config

    def generate(
        self,
        script_text: str,
        topic: Optional[str] = None,
        title_hint: Optional[str] = None,
        music_attribution: Optional[str] = None,
        asset_attributions: Optional[list[str]] = None,
    ) -> dict:
        """
        Generate and return metadata dict with keys:
        title, description, hashtags, tags.
        """
        gemini_key = os.getenv("GEMINI_API_KEY", "")
        if gemini_key:
            meta = self._generate_with_gemini(script_text, topic, title_hint)
            if meta:
                meta = self._add_attributions(meta, music_attribution, asset_attributions)
                return meta

        return self._generate_template(script_text, topic, title_hint, music_attribution, asset_attributions)

    def save(self, meta: dict, output_dir: str | Path) -> Path:
        """Write video_metadata.txt to output_dir."""
        out = Path(output_dir) / "video_metadata.txt"
        lines = [
            "# YouTube Video Metadata",
            "# Generated by AI-Shorts-Generator",
            "# Review and edit before uploading.",
            "",
            f"TITLE:\n{meta.get('title', '')}",
            "",
            f"DESCRIPTION:\n{meta.get('description', '')}",
            "",
            f"HASHTAGS:\n{' '.join(meta.get('hashtags', []))}",
            "",
            f"TAGS (comma-separated):\n{', '.join(meta.get('tags', []))}",
            "",
            "# ─── Attribution (include in description) ────────────────",
            meta.get("attribution_block", ""),
        ]
        out.write_text("\n".join(lines), encoding="utf-8")
        logger.info(f"Metadata saved: {out}")
        return out

    # ── Gemini generation ────────────────────────────────────────────────────

    def _generate_with_gemini(
        self,
        script_text: str,
        topic: Optional[str],
        title_hint: Optional[str],
    ) -> Optional[dict]:
        try:
            import google.generativeai as genai
            import json as json_mod

            api_key = os.getenv("GEMINI_API_KEY", "")
            genai.configure(api_key=api_key)
            model_name = self.cfg.get("gemini", {}).get("model", "gemini-1.5-flash")
            model = genai.GenerativeModel(model_name)

            topic_hint = f" Topic: {topic}." if topic else ""
            title_hint_str = f" Suggested title: {title_hint}." if title_hint else ""

            prompt = f"""You are a YouTube Shorts expert.{topic_hint}{title_hint_str}

Create viral-worthy metadata for this YouTube Short script.
Requirements:
- Title: max 60 chars, punchy, starts with an emoji, creates curiosity
- Description: 2–3 sentences expanding on the content, include key facts
- 5 hashtags: mix of niche (#JamesWebb) and broad (#Space #Science)
- 8 SEO tags: relevant keywords, no hashtag symbol

Return ONLY valid JSON (no markdown fences):
{{
  "title": "...",
  "description": "...",
  "hashtags": ["#tag1", "#tag2", "#tag3", "#tag4", "#tag5"],
  "tags": ["tag1", "tag2", "tag3", "tag4", "tag5", "tag6", "tag7", "tag8"]
}}

Script:
{script_text[:1500]}"""

            response = model.generate_content(prompt)
            raw = response.text.strip()
            raw = re.sub(r"^```json\s*", "", raw)
            raw = re.sub(r"```$", "", raw).strip()
            data = json_mod.loads(raw)
            logger.info("Metadata generated with Gemini")
            return data

        except Exception as e:
            logger.warning(f"Gemini metadata generation failed: {e}")
            return None

    # ── Template generation ───────────────────────────────────────────────────

    def _generate_template(
        self,
        script_text: str,
        topic: Optional[str],
        title_hint: Optional[str],
        music_attribution: Optional[str],
        asset_attributions: Optional[list[str]],
    ) -> dict:
        base_topic = topic or title_hint or "Amazing Facts"
        title = title_hint or f"🤯 {base_topic[:50]} #Shorts"
        words = script_text.split()[:20]
        description = " ".join(words) + "... Watch to learn more!"
        hashtags = ["#Shorts", "#YouTubeShorts", "#Facts", "#Learn", "#Viral"]
        tags = [
            base_topic.replace(" ", ""),
            "shorts",
            "youtube shorts",
            "facts",
            "learn",
            "educational",
            "viral",
            "trending",
        ]
        meta = {
            "title": title,
            "description": description,
            "hashtags": hashtags,
            "tags": tags,
        }
        return self._add_attributions(meta, music_attribution, asset_attributions)

    def _add_attributions(
        self,
        meta: dict,
        music_attribution: Optional[str],
        asset_attributions: Optional[list[str]],
    ) -> dict:
        attribution_lines = []
        if asset_attributions:
            attribution_lines.append("📷 Visual credits:")
            for attr in set(asset_attributions[:5]):  # Dedupe, limit to 5
                attribution_lines.append(f"  {attr}")
        if music_attribution:
            attribution_lines.append(f"🎵 {music_attribution}")
        attribution_lines.append("\n⚡ Generated with AI-Shorts-Generator")
        meta["attribution_block"] = "\n".join(attribution_lines)

        # Append attribution to description
        if attribution_lines:
            meta["description"] = (
                meta.get("description", "") + "\n\n" + meta["attribution_block"]
            )
        return meta
